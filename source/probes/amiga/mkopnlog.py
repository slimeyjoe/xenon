#!/usr/bin/env python3
"""Turn the first SECONDS of a VGM's YM2203 register stream into a C header for opnbench.

usage: mkopnlog.py FILE.vgm SECONDS OUT.h

The log is an array of {time in 1/44100 s, reg, val} entries, the same timing the sequencer
produces, so the benchmark exercises the core with real song data (voices, key-ons, SSG).
"""
import struct
import sys


def parse(path):
    d = open(path, 'rb').read()
    i = 0x34 + struct.unpack_from('<I', d, 0x34)[0]
    t = 0
    out = []
    while i < len(d):
        c = d[i]
        if c == 0x55:
            out.append((t, d[i + 1], d[i + 2])); i += 3
        elif c == 0x61:
            t += struct.unpack_from('<H', d, i + 1)[0]; i += 3
        elif c == 0x62:
            t += 735; i += 1
        elif c == 0x63:
            t += 882; i += 1
        elif 0x70 <= c <= 0x7f:
            t += (c & 15) + 1; i += 1
        elif c == 0x66:
            break
        elif c in (0x4f, 0x50):
            i += 2
        else:
            raise SystemExit('unknown VGM command %02X' % c)
    return out, t


def main():
    vgm, seconds, out = sys.argv[1], float(sys.argv[2]), sys.argv[3]
    ev, total = parse(vgm)
    limit = min(int(seconds * 44100), total)
    ev = [e for e in ev if e[0] < limit]
    with open(out, 'w') as f:
        f.write('/* generated by mkopnlog.py from %s: %d writes, %.2f s */\n' %
                (vgm.split('/')[-1], len(ev), limit / 44100.0))
        f.write('#define OPNLOG_SAMPLES %dUL\n' % limit)
        f.write('#define OPNLOG_COUNT %d\n' % len(ev))
        f.write('static const struct { unsigned long t; unsigned char reg, val; } opnlog[OPNLOG_COUNT] = {\n')
        for k, (t, r, v) in enumerate(ev):
            f.write('{%dUL,0x%02X,0x%02X},' % (t, r, v))
            if k % 6 == 5:
                f.write('\n')
        f.write('};\n')


if __name__ == '__main__':
    main()
